#!/usr/bin/env python3
"""Generate the conservative ancestry-parameter proof source; never change input."""
import argparse
import hashlib
import json
from pathlib import Path

OLD = r'''RECURSIVE AncN(_, _)
AncN(x, n) == IF n = 0 \/ parent[x] = NoThread THEN {}
              ELSE {parent[x]} \cup AncN(parent[x], n - 1)'''
NEW = '''CONSTANT ProofAncestry(_, _, _)
AncN(x, n) == ProofAncestry(parent, x, n)'''


def main():
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path, default=here.parent)
    parser.add_argument('--output-dir', type=Path, default=here)
    parser.add_argument('--check', action='store_true', help='Check generated bytes without writing files')
    args = parser.parse_args()
    source = (args.source_dir / 'Delegation.tla').read_bytes().decode('utf-8')
    header = 'MODULE Delegation '
    if source.count(OLD) != 1 or source.count(header) != 1:
        raise SystemExit('Source shape changed; review the ancestry abstraction before regenerating')
    generated = source.replace(header, 'MODULE DelegationS3Source ', 1).replace(OLD, NEW, 1)
    restored = generated.replace('MODULE DelegationS3Source ', header, 1).replace(NEW, OLD, 1)
    assert restored == source
    artifacts = {'DelegationS3Source.tla': generated.encode()}
    for name in ['RunBase.tla', 'ResultS3Proof.tla']:
        artifacts[name] = (args.source_dir / name).read_bytes()
    manifest = {
        'source_sha256': hashlib.sha256(source.encode()).hexdigest(),
        'generated_sha256': hashlib.sha256(generated.encode()).hexdigest(),
        'transform': 'Rename module; parameterize only AncN by arbitrary ProofAncestry(parent,x,n).',
        'scope': 'All ancestry operators; concrete recursive AncN is an instance. No state bounds.',
    }
    artifacts['s3-source-manifest.json'] = (json.dumps(manifest, indent=2) + '\n').encode()
    if args.check:
        for name, data in artifacts.items():
            path = args.output_dir / name
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit('Generated source check failed: ' + name)
    else:
        args.output_dir.mkdir(parents=True, exist_ok=True)
        for name, data in artifacts.items():
            (args.output_dir / name).write_bytes(data)
    print(json.dumps(manifest))


if __name__ == '__main__':
    main()
